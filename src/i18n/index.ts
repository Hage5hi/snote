// Lightweight i18n. Auto-detects from a saved choice, then the browser locale.
// Supported languages: English, Vietnamese, Chinese (Simplified), Japanese, Korean, French, Spanish, German, Portuguese.
import { createContext, useContext } from "react";

export type Lang = "en" | "vi" | "zh" | "ja" | "ko" | "fr" | "es" | "de" | "pt";

export const SUPPORTED_LANGS: Lang[] = ["en", "vi", "zh", "ja", "ko", "fr", "es", "de", "pt"];

export const LANG_NAMES: Record<Lang, { native: string; flag: string }> = {
  en: { native: "English", flag: "🇺🇸" },
  vi: { native: "Tiếng Việt", flag: "🇻🇳" },
  zh: { native: "中文", flag: "🇨🇳" },
  ja: { native: "日本語", flag: "🇯🇵" },
  ko: { native: "한국어", flag: "🇰🇷" },
  fr: { native: "Français", flag: "🇫🇷" },
  es: { native: "Español", flag: "🇪🇸" },
  de: { native: "Deutsch", flag: "🇩🇪" },
  pt: { native: "Português", flag: "🇵🇹" },
};

export const STORAGE_KEY = "lang";

export function isLang(v: unknown): v is Lang {
  return typeof v === "string" && (SUPPORTED_LANGS as string[]).includes(v);
}

export function detectFromNavigator(): Lang {
  if (typeof navigator === "undefined") return "en";
  const navLangs = (navigator.languages && navigator.languages.length > 0
    ? navigator.languages
    : [navigator.language || "en"]) as string[];
  for (const raw of navLangs) {
    const l = raw.toLowerCase();
    if (l.startsWith("vi")) return "vi";
    if (l.startsWith("zh")) return "zh";
    if (l.startsWith("ja")) return "ja";
    if (l.startsWith("ko")) return "ko";
    if (l.startsWith("fr")) return "fr";
    if (l.startsWith("es")) return "es";
    if (l.startsWith("de")) return "de";
    if (l.startsWith("pt")) return "pt";
    if (l.startsWith("en")) return "en";
  }
  return "en";
}

export function detectLang(): Lang {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (isLang(saved)) return saved;
  } catch {
    // localStorage blocked (private mode / disabled cookies) — try sessionStorage
    try {
      const saved = sessionStorage.getItem(STORAGE_KEY);
      if (isLang(saved)) return saved;
    } catch {
      // ignore
    }
  }
  return detectFromNavigator();
}

